const moduleDetails = new Set(customization_data.map(({ id }) => id));
const featuredDetails = new Set(featuredTdlModules.map(({ detailId }) => detailId));
const existingModules = customization_data.filter(({ id }) => !featuredDetails.has(id)).map((module) => ({
  id: module.id,
  title: module.title.trim(),
  category: existingCategories[module.id] ?? "Industry solutions",
  description: module.subtitle?.trim(),
  detailId: module.id,
}));
const pdfModules = Object.entries(pdfModuleGroups).flatMap(([category, titles]) => titles.map((title) => ({
  id: title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/-$/, ""),
  title,
  category,
})));

const tallyGroups = servicesData.find(({ id }) => id === "tally").categories.find(({ id }) => id === "tally-customise").items;
const enquiryOnly = [...new Map(tallyGroups.flatMap(({ services }) => services).map((module) => [module.slug, module])).values()]
  .filter(({ slug }) => !moduleDetails.has(slug) && slug !== "mis_dashboards")
  .map(({ slug, name }) => ({ id: slug, title: name, category: "GST & tax" }));

export const tdlCatalogue = [...featuredTdlModules, ...existingModules, ...pdfModules, ...enquiryOnly].map((module) => ({
  ...module,
  icon: module.icon ?? icons[module.category],
}));
